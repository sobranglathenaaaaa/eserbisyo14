import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createClient } from '@supabase/supabase-js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

function parseEnvFile(filePath) {
  const result = {};
  if (!fs.existsSync(filePath)) return result;

  const lines = fs.readFileSync(filePath, 'utf8').split(/\r?\n/);
  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;

    const idx = line.indexOf('=');
    if (idx < 0) continue;

    const key = line.slice(0, idx).trim();
    let value = line.slice(idx + 1).trim();

    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }

    if (key) result[key] = value;
  }

  return result;
}

function ensureEnv() {
  const envLocalPath = path.join(rootDir, '.env.local');
  const envVars = parseEnvFile(envLocalPath);
  for (const [key, value] of Object.entries(envVars)) {
    if (!process.env[key]) process.env[key] = value;
  }

  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const serviceRole = process.env.SUPABASE_SERVICE_ROLE_KEY;

  if (!url || !serviceRole) {
    throw new Error('Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY in .env.local');
  }

  return { url, serviceRole };
}

async function findAuthUserIdByEmail(admin, email) {
  let page = 1;
  const perPage = 200;

  while (true) {
    const { data, error } = await admin.auth.admin.listUsers({ page, perPage });
    if (error) throw new Error(`Unable to list users: ${error.message}`);

    const users = data?.users ?? [];
    const found = users.find((user) => (user.email ?? '').toLowerCase() === email.toLowerCase());
    if (found?.id) return found.id;

    if (users.length < perPage) return null;
    page += 1;
  }
}

async function ensureUserAndProfile(admin, account) {
  const email = account.email.trim().toLowerCase();
  let userId = null;

  const createResult = await admin.auth.admin.createUser({
    email,
    password: account.password,
    email_confirm: true,
    user_metadata: {
      full_name: account.fullName,
    },
  });

  if (!createResult.error && createResult.data.user?.id) {
    userId = createResult.data.user.id;
  } else {
    userId = await findAuthUserIdByEmail(admin, email);
    if (!userId) {
      throw new Error(`Unable to create or find auth user for ${email}: ${createResult.error?.message ?? 'unknown error'}`);
    }

    const { error: updateError } = await admin.auth.admin.updateUserById(userId, {
      password: account.password,
      email_confirm: true,
      user_metadata: {
        full_name: account.fullName,
      },
    });

    if (updateError) {
      throw new Error(`Unable to update auth user for ${email}: ${updateError.message}`);
    }
  }

  const { error: profileError } = await admin
    .from('profiles')
    .upsert(
      {
        id: userId,
        full_name: account.fullName,
        email,
        role: account.role,
        locale: 'en',
        is_deleted: false,
        is_verified: true,
      },
      { onConflict: 'id' }
    );

  if (profileError) {
    throw new Error(`Unable to upsert profile for ${email}: ${profileError.message}`);
  }

  return userId;
}

async function ensureDocumentTypes(admin) {
  const { data, error } = await admin.from('document_types').select('id').limit(1);
  if (error) {
    throw new Error(`Unable to query document types: ${error.message}`);
  }

  if ((data ?? []).length > 0) return;

  const seedRows = [
    { category: 'Certification', type: 'Barangay Clearance', price: 0, pricing_note: 'QA seed' },
    { category: 'Civil Registry', type: 'Barangay Certificate', price: 0, pricing_note: 'QA seed' },
    { category: 'Civil Registry', type: 'Certificate of Residency', price: 0, pricing_note: 'QA seed' },
  ];

  const { error: insertError } = await admin.from('document_types').insert(seedRows);
  if (insertError) {
    throw new Error(`Unable to seed document types: ${insertError.message}`);
  }
}

function writeQaEnv(accounts) {
  const qaEnvPath = path.join(rootDir, 'QA', '_shared', 'automated', '.env.qa');
  const lines = [
    '# Auto-generated by scripts/bootstrap-qa-accounts.mjs',
    'QA_BASE_URL=http://localhost:3000',
    'QA_TENANT_ID=default',
    '',
    `QA_RESIDENT_EMAIL=${accounts.resident.email}`,
    `QA_RESIDENT_PASSWORD=${accounts.resident.password}`,
    '',
    `QA_ADMIN_EMAIL=${accounts.admin.email}`,
    `QA_ADMIN_PASSWORD=${accounts.admin.password}`,
    '',
    `QA_STAFF_EMAIL=${accounts.staff.email}`,
    `QA_STAFF_PASSWORD=${accounts.staff.password}`,
    '',
  ];

  fs.writeFileSync(qaEnvPath, lines.join('\n'), 'utf8');
  return qaEnvPath;
}

async function main() {
  const { url, serviceRole } = ensureEnv();
  const admin = createClient(url, serviceRole, {
    auth: { autoRefreshToken: false, persistSession: false },
  });

  const accounts = {
    resident: {
      role: 'resident',
      fullName: 'QA Resident',
      email: 'qa.resident@eserbisyo.local',
      password: 'QaResident#2026!',
    },
    admin: {
      role: 'admin',
      fullName: 'QA Admin',
      email: 'qa.admin@eserbisyo.local',
      password: 'QaAdmin#2026!',
    },
    staff: {
      role: 'staff',
      fullName: 'QA Staff',
      email: 'qa.staff@eserbisyo.local',
      password: 'QaStaff#2026!',
    },
  };

  await ensureUserAndProfile(admin, accounts.resident);
  await ensureUserAndProfile(admin, accounts.admin);
  await ensureUserAndProfile(admin, accounts.staff);
  await ensureDocumentTypes(admin);

  const qaEnvPath = writeQaEnv(accounts);
  console.log(`QA accounts ready. Wrote env file: ${qaEnvPath}`);
  console.log('Use npm run qa:smoke:env then npx playwright show-report QA/reports/playwright-html');
}

main().catch((error) => {
  console.error(error.message || error);
  process.exit(1);
});
